import { QueryResult, StatuteEntry, PreemptionNote } from "@openlex/core";

export interface MemoOptions {
  author?: string;
  date?: string;
  title?: string;
  format?: "markdown" | "latex";
  includePreemption?: boolean;
  includeCourtHierarchy?: boolean;
}

/** Generate a publication-quality legal research memo */
export function toLegalMemo(result: QueryResult, options?: MemoOptions): string {
  const opts = options ?? {};
  const format = opts.format ?? "markdown";

  return format === "latex"
    ? toLatexMemo(result, opts)
    : toMarkdownMemo(result, opts);
}

function toMarkdownMemo(result: QueryResult, opts: MemoOptions): string {
  const lines: string[] = [];
  const title = opts.title ?? `Legal Research Memo: ${result.query.topic}`;
  const date = opts.date ?? new Date(result.timestamp).toISOString().split("T")[0];

  lines.push(`# ${title}`);
  lines.push("");
  if (opts.author) lines.push(`**Prepared by:** ${opts.author}`);
  lines.push(`**Date:** ${date}`);
  lines.push(`**Topic:** ${result.query.topic}`);
  if (result.query.state) lines.push(`**Jurisdiction:** ${result.query.state.toUpperCase()}`);
  lines.push("");
  lines.push("---");
  lines.push("");

  // Executive Summary
  lines.push("## Executive Summary");
  lines.push("");
  lines.push(`This memo surveys the legal landscape for **${result.query.topic}**`);
  if (result.query.state) {
    lines.push(`in **${result.query.state.toUpperCase()}** and at the federal level.`);
  } else {
    lines.push(`across ${result.authorities.length} jurisdiction(s).`);
  }
  lines.push(`A total of ${result.authorities.reduce((n, a) => n + a.statutes.length, 0)} statutes and ${result.authorities.reduce((n, a) => n + a.regulations.length, 0)} regulations were identified.`);
  lines.push("");

  // Detailed Analysis
  for (const auth of result.authorities) {
    lines.push(`## ${auth.jurisdiction.name}`);
    lines.push("");

    if (auth.statutes.length > 0) {
      lines.push("### Applicable Statutes");
      lines.push("");
      for (const s of auth.statutes) {
        lines.push(`#### ${s.fullCitation}`);
        lines.push("");
        lines.push(`**${s.title}**`);
        lines.push("");
        if (isStatuteEntry(s)) {
          if (s.keyProvisions.length > 0) {
            lines.push("**Key Provisions:**");
            for (const p of s.keyProvisions) {
              lines.push(`- ${p}`);
            }
            lines.push("");
          }
          if (s.penalties) {
            lines.push(`**Penalties:** ${s.penalties}`);
            lines.push("");
          }
          if (s.exceptions) {
            lines.push(`**Exceptions:** ${s.exceptions}`);
            lines.push("");
          }
        }
        if (s.url) {
          lines.push(`*Source:* [${s.fullCitation}](${s.url})`);
          lines.push("");
        }
      }
    }

    if (auth.regulations.length > 0) {
      lines.push("### Applicable Regulations");
      lines.push("");
      for (const r of auth.regulations) {
        lines.push(`- **${r.fullCitation}** — ${r.title} (${r.agency})`);
        if (r.url) lines.push(`  - [Source](${r.url})`);
      }
      lines.push("");
    }

    if (opts.includePreemption && auth.preemption.length > 0) {
      lines.push("### Federal-State Interaction");
      lines.push("");
      for (const p of auth.preemption) {
        lines.push(`- **${p.federalAuthority}** ${p.relationship} **${p.stateAuthority}**: ${p.description}`);
      }
      lines.push("");
    }

    if (opts.includeCourtHierarchy && auth.courts.length > 0) {
      lines.push("### Court Hierarchy");
      lines.push("");
      for (const c of auth.courts) {
        lines.push(`- ${c.name} (${c.abbreviation}) — ${c.level}`);
      }
      lines.push("");
    }
  }

  // Disclaimer
  lines.push("---");
  lines.push("");
  lines.push(`*${result.disclaimer}*`);
  lines.push("");
  lines.push(`*Generated by OpenLex on ${date}.*`);

  return lines.join("\n");
}

function toLatexMemo(result: QueryResult, opts: MemoOptions): string {
  const lines: string[] = [];
  const title = opts.title ?? `Legal Research Memo: ${result.query.topic}`;
  const date = opts.date ?? new Date(result.timestamp).toISOString().split("T")[0];

  lines.push("\\documentclass{article}");
  lines.push("\\usepackage{booktabs}");
  lines.push("\\usepackage{hyperref}");
  lines.push("\\usepackage[margin=1in]{geometry}");
  lines.push("");
  lines.push(`\\title{${escapeLatex(title)}}`);
  if (opts.author) lines.push(`\\author{${escapeLatex(opts.author)}}`);
  lines.push(`\\date{${date}}`);
  lines.push("");
  lines.push("\\begin{document}");
  lines.push("\\maketitle");
  lines.push("");

  // Summary
  lines.push("\\section{Executive Summary}");
  const statCount = result.authorities.reduce((n, a) => n + a.statutes.length, 0);
  const regCount = result.authorities.reduce((n, a) => n + a.regulations.length, 0);
  lines.push(`This memo surveys the legal landscape for \\textbf{${escapeLatex(result.query.topic)}} across ${result.authorities.length} jurisdiction(s). A total of ${statCount} statutes and ${regCount} regulations were identified.`);
  lines.push("");

  // Per jurisdiction
  for (const auth of result.authorities) {
    lines.push(`\\section{${escapeLatex(auth.jurisdiction.name)}}`);
    lines.push("");

    if (auth.statutes.length > 0) {
      lines.push("\\subsection{Applicable Statutes}");
      lines.push("\\begin{itemize}");
      for (const s of auth.statutes) {
        lines.push(`  \\item \\textbf{${escapeLatex(s.fullCitation)}} --- ${escapeLatex(s.title)}`);
      }
      lines.push("\\end{itemize}");
      lines.push("");
    }

    if (auth.regulations.length > 0) {
      lines.push("\\subsection{Applicable Regulations}");
      lines.push("\\begin{itemize}");
      for (const r of auth.regulations) {
        lines.push(`  \\item \\textbf{${escapeLatex(r.fullCitation)}} --- ${escapeLatex(r.title)} (${escapeLatex(r.agency)})`);
      }
      lines.push("\\end{itemize}");
      lines.push("");
    }
  }

  lines.push("\\vfill");
  lines.push(`\\noindent\\textit{${escapeLatex(result.disclaimer)}}`);
  lines.push("");
  lines.push("\\end{document}");

  return lines.join("\n");
}

function isStatuteEntry(s: unknown): s is StatuteEntry {
  return typeof s === "object" && s !== null && "keyProvisions" in s;
}

function escapeLatex(s: string): string {
  return s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/[&%$#_{}]/g, (m) => `\\${m}`)
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}");
}
