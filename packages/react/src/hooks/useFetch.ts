import { useState, useEffect } from "react";
import { useOpenLexConfig, UseQueryResult } from "./useOpenLex";

/** Internal fetch hook — shared by all data hooks */
export function useFetch<T>(path: string, enabled = true): UseQueryResult<T> {
  const { baseUrl } = useOpenLexConfig();
  const [data, setData] = useState<T | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!enabled || !path) {
      setData(null);
      setLoading(false);
      setError(null);
      return;
    }

    let cancelled = false;
    setLoading(true);
    setError(null);

    const url = `${baseUrl.replace(/\/$/, "")}${path}`;

    fetch(url)
      .then((res) => {
        if (!res.ok) throw new Error(`HTTP ${res.status}: ${res.statusText}`);
        return res.json();
      })
      .then((json) => {
        if (!cancelled) {
          setData(json as T);
          setLoading(false);
        }
      })
      .catch((err) => {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : "Unknown error");
          setLoading(false);
        }
      });

    return () => {
      cancelled = true;
    };
  }, [baseUrl, path, enabled]);

  return { data, loading, error };
}
